# Database configuration
# In Docker Compose, DATABASE_URL points to postgres://...
# For local execution outside Docker without PostgreSQL, gracefully fall back to SQLite
default_db_url = os.getenv('DATABASE_URL')
import socket

def is_db_host_available(db_url):
    if not db_url:
        return False
    try:
        parsed = dj_database_url.parse(db_url)
        host = parsed.get('HOST')
        if not host:
            return False
        # Test if host resolves
        socket.getaddrinfo(host, parsed.get('PORT') or 5432)
        return True
    except Exception:
        return False

if default_db_url and is_db_host_available(default_db_url):
    DATABASES = {
        'default': dj_database_url.config(
            default=default_db_url,
            conn_max_age=600,
            conn_health_checks=True,
        )
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }

